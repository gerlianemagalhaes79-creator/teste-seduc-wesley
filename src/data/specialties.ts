// Helper to generate full personalized syllabus topics based on selected specialty
export function generateTopicsForSpecialty(specialtyId: SpecialtyId): StudyTopic[] {
  const spec = SPECIALTIES.find((s) => s.id === specialtyId) || SPECIALTIES[0];
  
  // Clone common topics with attached subtopics
  const fullTopics: StudyTopic[] = COMMON_STUDY_TOPICS.map((t, idx) => {
    const subs = COMMON_SUBTOPICS_MAP[t.id] || generateDefaultSubtopicsForTopic(t.id, t.title, t.moduleName);
    let modulePrefix = "1.";
    if (t.moduleId === "educacao_brasileira_didatica") modulePrefix = "2.";
    else if (t.moduleId === "administracao_publica") modulePrefix = "3.";
    else if (t.moduleId === "indicadores_educacionais") modulePrefix = "4.";
    
    return {
      ...t,
      syllabusCode: `${modulePrefix}${idx + 1}`,
      funeceIncidencePercent: t.importanceInFunece.includes("Altíssima") ? 95 : 85,
      subtopics: subs.map((sub) => ({ ...sub })),
    };
  });

  // Distribute specific topics across days
  spec.coreSpecificTopics.forEach((topicTitle, index) => {
    const topicNum = index + 1;
    const dayOfWeek = (index % 6) + 1; // 1 to 6 (Seg a Sab)
    const topicId = `spec-${specialtyId}-${topicNum}`;
    
    // Find specialty-specific subtopics if available
    const customSubs = SPECIALTY_SUBTOPICS_GENERATOR[specialtyId]?.[topicNum];
    const subtopics = customSubs
      ? customSubs.map((sub) => ({ ...sub }))
      : generateDefaultSubtopicsForTopic(topicId, topicTitle, `Específica: ${spec.name}`);

    fullTopics.push({
      id: topicId,
      moduleId: "conhecimentos_especificos",
      moduleName: `Específica: ${spec.name}`,
      title: topicTitle,
      description: `Tópico aprofundado do edital SEDUC-CE para ${spec.name}, com ênfase no perfil conceitual e nas questões da banca FUNECE / CEV-UECE.`,
      specialtyId: specialtyId,
      importanceInFunece: index < 6 ? "Altíssima (Foco Máximo)" : "Alta",
      estimatedMinutes: 80,
      isCompleted: false,
      isDelayed: false,
      scheduledDayOfWeek: dayOfWeek,
      syllabusCode: `P2.${topicNum}`,
      funeceIncidencePercent: index < 5 ? 98 : index < 10 ? 92 : 85,
      keyFormulasOrLaws: `Conhecimento Específico ${spec.name} - Diário Oficial do Estado do Ceará`,
      subtopics: subtopics,
    });
  });

  return fullTopics;
}
